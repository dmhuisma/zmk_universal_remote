#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.11,<3.15"
# dependencies = ["pyyaml"]
# ///
"""Prints a Home Assistant automation that handles every remote button, to
start editing from.

    uv run tools/gen_hass_automation.py home_assistant/bthome_buttons.yaml \\
        [--address XX:XX:XX:XX:XX:XX] > universal_remote.yaml

The automation triggers on each button's tap and long press, with a trigger ID
such as light_living_room_left_tap, and a choose branch per trigger that only
writes to the system log. Replace those actions with real ones.

The buttons file is checked against bthome-buttons and bthome-button-numbers
in the UI devicetree first, so it cannot drift from what the remote sends.
"""

import argparse
import json
import re
import sys
from pathlib import Path

import yaml

UI_DTSI = (
    Path(__file__).resolve().parent.parent
    / "boards/shields/universal_remote/universal_remote_ui.dtsi"
)

PRESSES = {"tap": "tapped", "long_press": "long pressed"}
DIMMER_EVENTS = {"rotate_right", "rotate_left"}


def dtsi_property(text: str, name: str) -> str:
    match = re.search(rf"\b{re.escape(name)}\s*=(.*?);", text, re.DOTALL)
    if match is None:
        sys.exit(f"{UI_DTSI}: no {name} property")
    # Drop the // comments between the groups of cells.
    return re.sub(r"//[^\n]*", "", match.group(1))


def check_against_dtsi(buttons: list[dict]) -> None:
    text = UI_DTSI.read_text()
    widgets = re.findall(r"&(\w+)", dtsi_property(text, "bthome-buttons"))
    numbers = [int(n, 0) for n in re.findall(r"\b(?:0x[0-9a-fA-F]+|\d+)\b",
                                             dtsi_property(text, "bthome-button-numbers"))]
    if len(widgets) != len(numbers):
        sys.exit(f"{UI_DTSI}: bthome-buttons and bthome-button-numbers differ in length")

    expected = dict(zip(widgets, numbers))
    listed = {button["id"]: button["steps"] for button in buttons}
    if listed != expected:
        for id_ in sorted(expected.keys() - listed.keys()):
            print(f"missing from the buttons file: {id_} (steps {expected[id_]})", file=sys.stderr)
        for id_ in sorted(listed.keys() - expected.keys()):
            print(f"not in bthome-buttons: {id_}", file=sys.stderr)
        for id_ in sorted(listed.keys() & expected.keys()):
            if listed[id_] != expected[id_]:
                print(f"{id_}: steps {listed[id_]} here, {expected[id_]} in the devicetree",
                      file=sys.stderr)
        sys.exit(f"The buttons file does not match {UI_DTSI}")


def check_events(buttons: list[dict]) -> None:
    seen: dict[tuple[str, int], str] = {}
    for button in buttons:
        if set(button["events"]) != set(PRESSES):
            sys.exit(f"{button['id']}: events must list exactly {', '.join(PRESSES)}")
        for press, event_type in button["events"].items():
            if event_type not in DIMMER_EVENTS:
                sys.exit(f"{button['id']}: unknown event type {event_type}")
            key = (event_type, button["steps"])
            if key in seen:
                sys.exit(f"{button['id']} {press} sends the same event as {seen[key]}")
            seen[key] = f"{button['id']} {press}"


def quote(value: str) -> str:
    # A JSON string is a valid double-quoted YAML scalar.
    return json.dumps(value, ensure_ascii=False)


def automation(buttons: list[dict], address: str, source: str) -> str:
    lines = [
        f"# Generated by tools/gen_hass_automation.py from {source}.",
        "# Each choose branch only logs the press; replace its action with the real one.",
        "alias: Universal remote",
        "description: Touchscreen buttons on the living room universal remote, sent over BTHome.",
        # Presses can arrive faster than slower actions finish.
        "mode: queued",
        "max: 10",
        "triggers:",
    ]
    for button in buttons:
        for press, event_type in button["events"].items():
            lines += [
                "  - trigger: event",
                f"    id: {button['id']}_{press}",
                "    event_type: bthome_ble_event",
                "    event_data:",
                f"      address: {quote(address)}",
                f"      event_type: {event_type}",
                "      event_properties:",
                f"        steps: {button['steps']}",
            ]

    lines += ["conditions: []", "actions:", "  - choose:"]
    for button in buttons:
        name = f"{button['screen']} / {button['label']}"
        lines.append(f"      # Button {button['steps']}, {name}: {button['target']}")
        for press in button["events"]:
            message = f"{name} {PRESSES[press]} (button {button['steps']})"
            lines += [
                "      - conditions:",
                "          - condition: trigger",
                f"            id: {button['id']}_{press}",
                "        sequence:",
                "          - action: system_log.write",
                "            data:",
                "              level: info",
                "              logger: universal_remote",
                f"              message: {quote(message)}",
            ]

    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("buttons", type=Path, help="the buttons file, home_assistant/bthome_buttons.yaml")
    parser.add_argument("--address", default="XX:XX:XX:XX:XX:XX",
                        help="the remote's Bluetooth address, as Home Assistant shows it")
    args = parser.parse_args()

    buttons = yaml.safe_load(args.buttons.read_text())["buttons"]
    check_events(buttons)
    check_against_dtsi(buttons)
    sys.stdout.write(automation(buttons, args.address.upper(), args.buttons.as_posix()))


if __name__ == "__main__":
    main()

#!/usr/bin/env bash
# Generates the UI's icon font from Material Design Icons, the icon set Home
# Assistant uses. Both outputs are committed, so building the firmware does not
# need Node; rerun this only after changing ICONS below.
#
#   src/fonts/ui_icons_28.c                     the LVGL font, ui_icons_28
#   boards/shields/universal_remote/ui_icons.h  a UTF-8 string per icon,
#                                               e.g. UI_ICON_FLOOR_LAMP
#
# MDI's codepoints sit above U+F0000, which take 4 bytes of UTF-8. Each icon is
# remapped into the private use area from U+E000 instead, in ICONS order.
#
# Needs node and npm (for npx).

set -euo pipefail

MDI_VERSION=7.4.47
LV_FONT_CONV_VERSION=1.5.3
SIZE=28

# MDI icon names, as listed on https://pictogrammers.com/library/mdi/.
ICONS=(
    # Tab bar
    lightbulb-group
    television
    dots-horizontal-circle-outline
    # Lights
    floor-lamp
    light-recessed
    ceiling-light
    lightbulb
    movie-open
    brightness-7
    weather-night
    lightbulb-off
    # TV
    play-box-multiple
    youtube
    video-input-hdmi
    volume-off
    rewind
    play-pause
    fast-forward
    # More
    thermostat
    robot-vacuum
    chevron-left
    chevron-right
    # Climate
    minus
    plus
    fire
    snowflake
    sun-snowflake-variant
    power
    # Vacuums
    pause
    home-import-outline
    map-marker
    # Screen brightness, on the More screen
    brightness-6
)

root=$(cd "$(dirname "$0")/.." && pwd)
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

(cd "$work" && npm pack --silent "@mdi/font@$MDI_VERSION" >/dev/null && tar -xzf mdi-font-*.tgz)
variables="$work/package/scss/_variables.scss"
ttf="$work/package/fonts/materialdesignicons-webfont.ttf"

header="$root/boards/shields/universal_remote/ui_icons.h"
font="$root/src/fonts/ui_icons_28.c"
mkdir -p "$(dirname "$font")"

ranges=()
{
    echo "// Generated by tools/gen_icon_font.sh from @mdi/font $MDI_VERSION; do not edit."
    echo "// Each string is one glyph of the ui_icons_28 font."
    echo
    echo "#pragma once"
    echo
} >"$header"

target=$((0xE000))
for icon in "${ICONS[@]}"; do
    # Lines look like:   "floor-lamp": F08DD,
    codepoint=$(sed -n "s/^ *\"$icon\": *\([0-9A-Fa-f]*\),\?$/\1/p" "$variables")
    if [[ -z "$codepoint" ]]; then
        echo "Unknown MDI icon: $icon" >&2
        exit 1
    fi

    ranges+=(-r "0x$codepoint=>$(printf '0x%04X' "$target")")

    # A codepoint in U+E000-U+EFFF is 1110xxxx 10xxxxxx 10xxxxxx in UTF-8.
    utf8=$(printf '\\x%02x\\x%02x\\x%02x' \
        $((0xE0 | (target >> 12))) $((0x80 | ((target >> 6) & 0x3F))) $((0x80 | (target & 0x3F))))
    name=$(echo "$icon" | tr 'a-z-' 'A-Z_')
    printf '#define UI_ICON_%s "%s" // mdi:%s\n' "$name" "$utf8" "$icon" >>"$header"

    target=$((target + 1))
done

# Relative paths keep the options lv_font_conv records in the file the same
# from run to run.
(cd "$work" && npx --yes "lv_font_conv@$LV_FONT_CONV_VERSION" \
    --font "${ttf#"$work"/}" "${ranges[@]}" \
    --size "$SIZE" --bpp 4 --no-compress \
    --format lvgl --lv-font-name ui_icons_28 --lv-include lvgl.h \
    -o ui_icons_28.c)
mv "$work/ui_icons_28.c" "$font"

echo "Wrote $font and $header"
